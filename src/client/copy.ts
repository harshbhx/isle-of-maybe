/** Fill `{key}` placeholders. Unknown keys stay visible so mistakes are easy to spot. */
export const fmt = (
  template: string,
  vars: Record<string, string | number>
): string =>
  template.replace(/\{(\w+)\}/g, (m, k: string) =>
    k in vars ? String(vars[k]) : m
  );
